from typing import List, Optional, Protocol

from domain.modelo import (
    Dispositivo, EstadoPlanta, EvaluacionMatera, Lectura, Planta, RangoEspecie, Usuario,
)


class TablaReferenciaPort(Protocol):
    # En la fase 1 era EspecieRepository (obtener_por_nombre, obtener_todas_las_especies).
    def por_especie(self, nombre: str) -> Optional[RangoEspecie]: ...
    def todas(self) -> List[RangoEspecie]: ...


class HistorialLecturasPort(Protocol):
    def guardar(self, planta_id: str, lectura: Lectura, evaluacion: EvaluacionMatera) -> bool: ...  # False si duplicada
    def ultima(self, planta_id: str) -> Optional[EstadoPlanta]: ...
    def historial(self, planta_id: str, limite: int) -> List[EstadoPlanta]: ...


class PlantaRepositorioPort(Protocol):
    def guardar(self, planta: Planta) -> None: ...
    def por_id(self, planta_id: str) -> Optional[Planta]: ...
    def de_usuario(self, usuario_id: str) -> List[Planta]: ...


class DispositivoRepositorioPort(Protocol):
    def guardar(self, dispositivo: Dispositivo) -> None: ...
    def por_id(self, dispositivo_id: str) -> Optional[Dispositivo]: ...
    def por_codigo(self, codigo: str) -> Optional[Dispositivo]: ...


class UsuarioRepositorioPort(Protocol):
    def guardar(self, usuario: Usuario) -> None: ...                 # lanza UsuarioYaExiste
    def por_email(self, email: str) -> Optional[Usuario]: ...
    def por_id(self, usuario_id: str) -> Optional[Usuario]: ...


class EmisorTokenPort(Protocol):
    def token_usuario(self, usuario_id: str) -> str: ...
    def token_dispositivo(self, dispositivo_id: str, planta_id: str) -> str: ...


class HasherPasswordPort(Protocol):
    def hashear(self, password: str) -> str: ...
    def coincide(self, password: str, password_hash: str) -> bool: ...
